"""Synthetic stand-in for the CMS snapshot, for testing the pipeline before registration.

Values are made up (no CMS values were viewed). File names and the column names the pipeline reads mirror the real
files, including their quirks: M/D/YYYY dates (with " 0:00" in the PY2019 January enrollment file), ACO_Num in PY2016-17,
Sav_Rate in PY2021, AGDU/AGND vs AGED_Dual/AGED_NonDual, "*" suppression markers, ACOs with no PY2019 record, and
early-renewer rows in the PY2022 results file that the loader must drop.

`generate` also computes section 4.3 independently in numpy, so tests can compare the SQL against it.
"""

import warnings
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
import pandas as pd

from ratchet import config

TYPES = config.TYPES
RESULTS_SHARE_COLUMNS = {"ESRD": "N_AB_Year_ESRD_PY", "DIS": "N_AB_Year_DIS_PY", "AGDU": "N_AB_Year_AGED_Dual_PY", "AGND": "N_AB_Year_AGED_NonDual_PY"}

# Every column the SQL reads, by file group; tests check these against the real headers (first row only).
REQUIRED_COLUMNS = {
    "enrollment_2021": [
        "aco_id",
        "agreement_period_num",
        "current_start_date",
        "basic_track",
        "basic_track_level",
        "enhanced_track",
        "high_revenue_aco",
        "prospective_assignment",
    ],
    "results_2022_by": [f"{c}_{t}_BY{b}" for c in ("Per_Capita_Exp_ALL", "CMS_HCC_RiskScore") for t in TYPES for b in (1, 2, 3)],
    "results_2023_2024": ["ACO_ID", "Agreement_Period_Num", "Current_Start_Date", "Per_Capita_Exp_TOTAL_PY"],
    "results": ["ACO_ID", "Sav_rate", "N_AB", "UpdatedBnchmk", "HistBnchmk", "Current_Start_Date", "Per_Capita_Exp_TOTAL_PY", "N_Ben_Female", "N_Ben_Male"]
    + [f"N_Ben_Age_{b}" for b in ("0_64", "65_74", "75_84", "85plus")]
    + [f"Per_Capita_Exp_ALL_{t}_PY" for t in TYPES]
    + [f"CMS_HCC_RiskScore_{t}_PY" for t in TYPES]
    + list(RESULTS_SHARE_COLUMNS.values()),
    "results_aco_num": ["ACO_Num", "Sav_rate"],
    "results_2018": ["ACO_ID", "Sav_rate"],
    "county": ["STATE_ID", "COUNTY_ID"] + [f"PER_CAPITA_EXP_{t}" for t in TYPES] + [f"PERSON_YEARS_{t}" for t in TYPES] + [f"AVG_RISK_SCORE_{t}" for t in TYPES],
    "assignment": ["ACO_ID", "State_Name", "State_ID", "County_ID", "Tot_AB_Psn_Yrs"] + [f"AB_Psn_Yrs_{t}" for t in TYPES],
}

YEARS = (2019, 2020, 2021)
STATE_NAMES = {1: "Texas", 2: "Ohio", 3: "California"}  # South, Midwest, West
TYPE_BASE_PC = {"ESRD": 85_000.0, "DIS": 12_000.0, "AGDU": 20_000.0, "AGND": 11_000.0}
TYPE_BASE_PY = {"ESRD": 60.0, "DIS": 900.0, "AGDU": 800.0, "AGND": 6_000.0}


@dataclass
class Truth:
    """Ground truth for the synthetic snapshot."""

    acos: pd.DataFrame  # one row per ACO: kind, cohort, group, step, and the section 4.3 quantities
    unrecoverable: str  # ACO with two hidden person-year types: shares unknown, so it is excluded
    zero_share: str  # ACO with zero ESRD share and suppressed ESRD spending (must still be constructed)
    imputed_ids: list[str] = field(default_factory=list)  # hidden values filled by the section 3 rules
    early_ids: list[str] = field(default_factory=list)


def _mdy(year: int, month: int = 1, day: int = 1, suffix: str = "") -> str:
    return f"{month}/{day}/{year}{suffix}"


def generate(
    out_dir: Path,
    seed: int = 0,
    n_base=(150, 120),
    n_validation: int = 80,
    hist_noise: float = 0.0,
    by_noise: float = 0.0,
    beta_pull: float = 1.0,
    beta_own: float = 0.6,
    did_effect: float = -0.04,
) -> Truth:
    rng = np.random.default_rng(seed)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / config.SYNTHETIC_MARKER).write_text("Synthetic data generated by ratchet.synthetic; not CMS data.\n")

    # Counties: 3 states x 15 counties; spending grows by year.
    states, counties = np.repeat([1, 2, 3], 15), np.tile(np.arange(1, 16) * 10 + 1, 3)
    n_c = len(states)
    level = rng.lognormal(0, 0.15, n_c)
    county_pc = {y: {t: TYPE_BASE_PC[t] * level * rng.lognormal(0, 0.05, n_c) * (1.04 ** (y - 2019)) for t in TYPES} for y in YEARS}
    county_py = {y: {t: TYPE_BASE_PY[t] * rng.lognormal(0, 0.4, n_c) for t in TYPES} for y in YEARS}
    county_ok = {y: {t: np.ones(n_c, bool) for t in TYPES} for y in YEARS}
    county_ok[2020]["ESRD"][7] = False  # one suppressed county cell
    # County mean risk scores: higher-spending counties are somewhat sicker.
    county_risk = {y: {t: np.sqrt(level) * rng.lognormal(0, 0.06, n_c) for t in TYPES} for y in YEARS}

    # ACOs.
    n19, n20 = n_base
    kinds = ["base19"] * n19 + ["base20"] * n20 + ["valid"] * n_validation + ["other"] * 20
    n = len(kinds)
    ids = [f"A{1000 + i}" for i in range(n)]
    kind = np.array(kinds)
    prior = rng.choice(["new", "initial2016", "renewal2017"], size=n, p=[0.45, 0.4, 0.15])
    prior[kind == "valid"] = rng.choice(["initial2018", "renewal2018"], size=(kind == "valid").sum(), p=[0.6, 0.4])
    prior[kind == "other"] = "new"
    step = np.where(kind == "valid", np.where(prior == "renewal2018", 2, 1), np.where(prior == "renewal2017", 3, 2))

    # Assignment: each ACO in 3-6 counties of one state, person-years by type (ESRD present in every county).
    ab = np.zeros((n, n_c, len(TYPES)))
    home_state = np.empty(n, int)
    for i in range(n):
        home = home_state[i] = rng.integers(1, 4)
        chosen = rng.choice(np.flatnonzero(states == home), size=rng.integers(3, 7), replace=False)
        for k, t in enumerate(TYPES):
            ab[i, chosen, k] = np.round(TYPE_BASE_PY[t] * 0.2 * rng.lognormal(0, 0.5, len(chosen)), 1)
    shares_py = ab.sum(axis=1)  # PY2021 person-years by type, consistent with assignment
    # Suppression cases (section 3): 1 zero ESRD share; 2 ESRD hidden in PY2020 only (rule 2); 3 ESRD hidden in every
    # year (rule 3); 4 ESRD person-years hidden (recovered from the total); 5 two person-year types hidden (excluded).
    zero_share, some_hidden, all_hidden, share_hidden, unrecoverable = 1, 2, 3, 4, 5
    py_hidden = np.zeros((n, len(TYPES)), bool)
    py_hidden[share_hidden, 0] = True
    py_hidden[unrecoverable, :2] = True
    shares_py[zero_share, 0] = 0.0
    ab[zero_share, :, 0] = 0.0
    # Hidden ACO risk scores: 6 ESRD in PY2020 (that year unrestated); 7 ESRD in PY2021 (regional risk used instead).
    aco_risk = rng.lognormal(0, 0.1, (n, len(YEARS), len(TYPES)))
    risk_hidden = np.zeros((n, len(YEARS), len(TYPES)), bool)
    risk_hidden[6, 1, 0] = True
    risk_hidden[7, 2, 0] = True

    # Regional spending (425.601(c)-(d)): risk-standardized, the weighted county risk, and unadjusted.
    eff = rng.lognormal(-0.03, 0.08, n)
    region_std, reg_risk, region_raw = (np.full((n, len(YEARS), len(TYPES)), np.nan) for _ in range(3))
    for y_i, y in enumerate(YEARS):
        for k, t in enumerate(TYPES):
            ok = county_ok[y][t]
            wts = ab[:, :, k] * ok
            with np.errstate(invalid="ignore", divide="ignore"):
                region_std[:, y_i, k] = (wts * np.where(ok, county_pc[y][t] / county_risk[y][t], 0)).sum(1) / wts.sum(1)
                reg_risk[:, y_i, k] = (wts * county_risk[y][t]).sum(1) / wts.sum(1)
                region_raw[:, y_i, k] = (wts * np.where(ok, county_pc[y][t], 0)).sum(1) / wts.sum(1)
    # Regional spending at the ACO's case mix (425.601(a)(8)(i)(C)); a hidden ACO score falls back to the regional score.
    region = region_std * np.where(risk_hidden, reg_risk, aco_risk)
    own = region_std * aco_risk * eff[:, None, None] * rng.lognormal(0, 0.03, region_std.shape)
    own[zero_share, :, 0] = np.nan  # suppressed, share zero
    own[some_hidden, 1, 0] = np.nan
    own[all_hidden, :, 0] = np.nan
    has_py2019 = ~((kind == "base20") & (prior == "new")) & (kind != "other")

    # Current (PY2021 updated) benchmark: own spending shifted by the ACO's ratchet position.
    share = shares_py / shares_py.sum(1, keepdims=True)
    own21_w = np.nansum(share * np.nan_to_num(own[:, 2, :]), axis=1)
    current = own21_w * rng.lognormal(0.0, 0.05, n)

    # Section 4.3 in numpy (independent of the SQL).
    national = {y: {} for y in YEARS}
    for y in YEARS:
        for t in TYPES:
            ok = county_ok[y][t]
            national[y][t] = (county_pc[y][t][ok] * county_py[y][t][ok]).sum() / county_py[y][t][ok].sum()
    tot = ab.sum(2)
    county_total_2021 = sum(county_py[2021][t] for t in TYPES)
    s = (tot * (tot / county_total_2021)).sum(1) / tot.sum(1)
    factor = np.empty((n, len(YEARS), len(TYPES)))
    for k, t in enumerate(TYPES):
        for y_i, y in enumerate(YEARS):
            factor[:, y_i, k] = s * national[2021][t] / national[y][t] + (1 - s) * region_std[:, 2, k] / region_std[:, y_i, k]
    pos = share > 0
    nat21 = np.array([national[2021][t] for t in TYPES])
    shares_known = py_hidden.sum(1) <= 1
    w_below = np.where(step == 1, 0.35, 0.50)
    w_above = np.select([step == 1, step == 2, step == 3], [0.15, 0.25, 0.35], 0.50)
    reg_w = np.where(pos, share * np.nan_to_num(region[:, 2, :]), 0).sum(1)
    reg_raw_w = np.where(pos, share * np.nan_to_num(region_raw[:, 2, :]), 0).sum(1)

    def construct(by_first: int) -> dict:
        """Steps 1-5 for benchmark years by_first-2021 (2019 for the main analysis, 2020 for robustness item 6)."""
        record = np.ones((n, len(YEARS)), bool)
        record[~has_py2019, 0] = False
        record[:, : by_first - 2019] = False
        shown = ~np.isnan(own) & record[:, :, None]
        # Rule 3 ratio: own-to-region over shown types with positive share, per ACO and year.
        valid = shown & pos[:, None, :] & ~np.isnan(region)
        with np.errstate(invalid="ignore", divide="ignore"):
            ratio = np.where(valid, share[:, None, :] * np.nan_to_num(own), 0).sum(2) / np.where(valid, share[:, None, :] * np.nan_to_num(region), 0).sum(2)
        n_shown = shown.sum(1)
        filled = np.where(n_shown[:, None, :] > 0, own, region * ratio[:, :, None])
        # BY1-BY2 restated to BY3 case mix (425.601(a)(3)); a hidden score in that year or PY2021 leaves the year unrestated.
        restate_missing = risk_hidden | risk_hidden[:, 2:3, :]
        restate = np.where(restate_missing, 1.0, aco_risk[:, 2:3, :] / aco_risk)
        trended = np.where(record[:, :, None], filled * factor * restate, np.nan)
        with np.errstate(invalid="ignore"), warnings.catch_warnings():
            warnings.simplefilter("ignore", RuntimeWarning)
            rebased = np.nanmean(trended, axis=1)
        hidden_own = (record[:, :, None] & (np.isnan(own) | restate_missing)).any(1)
        imputed = (pos & ((n_shown == 0) | hidden_own | risk_hidden[:, 2, :])).any(1) | py_hidden.any(1)
        reb_w = np.where(pos, share * np.nan_to_num(rebased), 0).sum(1)
        w = np.where(reb_w < reg_w, w_below, w_above)
        raw_adj = w[:, None] * (region[:, 2, :] - rebased)
        adj = np.clip(raw_adj, -0.05 * nat21, 0.05 * nat21)
        ok_all = np.all(~pos | (~np.isnan(rebased) & ~np.isnan(region[:, 2, :])), axis=1) & shares_known
        adj_w = np.where(pos, share * np.nan_to_num(adj), 0).sum(1)
        new = np.where(ok_all, reb_w + adj_w, np.nan)
        return {"reb_w": reb_w, "w": w, "capped": (np.abs(raw_adj) > 0.05 * nat21) & pos, "ok_all": ok_all, "adj_w": adj_w, "new": new, "imputed": imputed}

    main, by23 = construct(2019), construct(2020)
    reb_w, w, capped, ok_all, adj_w, new, imputed = (main[k] for k in ("reb_w", "w", "capped", "ok_all", "adj_w", "new", "imputed"))
    acos = pd.DataFrame(
        {
            "aco_id": ids,
            "kind": kind,
            "prior": prior,
            "step": step,
            "w": w,
            "s": s,
            "new_bnchmk": new,
            "current_bnchmk": current,
            "gain": np.where(ok_all, 100 * (new - current) / current, np.nan),
            "own": np.where(ok_all, 100 * (reb_w - current) / current, np.nan),
            "regional_comp": np.where(ok_all, 100 * adj_w / current, np.nan),
            "pull": np.where(shares_known, 100 * (reg_w - current) / current, np.nan),
            "pull_unadjusted": np.where(shares_known, 100 * (reg_raw_w - current) / current, np.nan),
            "imputed": imputed & shares_known,
            "any_cap": capped.any(1),
            "has_py2019": has_py2019,
            "census_region": [{1: "South", 2: "Midwest", 3: "West"}[h] for h in home_state],
            "own_by23": np.where(by23["ok_all"], 100 * (by23["reb_w"] - current) / current, np.nan),
            "gain_by23": np.where(by23["ok_all"], 100 * (by23["new"] - current) / current, np.nan),
        }
    )

    # Groups among base ACOs: leavers at random; early renewal more likely with higher pull and own component.
    base = acos.kind.isin(["base19", "base20"]).to_numpy()
    z = lambda x: (x - np.nanmean(x[base])) / np.nanstd(x[base])  # noqa: E731
    logit = -2.3 + beta_pull * z(acos.pull.to_numpy()) + beta_own * np.nan_to_num(z(acos.own.to_numpy()))
    early = base & (rng.random(n) < 1 / (1 + np.exp(-logit)))
    leaver = base & ~early & (rng.random(n) < 0.08)
    acos["grp"] = np.where(~base, None, np.where(early, "early", np.where(leaver, "leaver", "stayer")))
    acos["cohort"] = np.where(kind == "base19", "2019-07", np.where(kind == "base20", "2020-01", None))
    # PY2023-PY2024 histories (section 4.5): later renewals and exits, as seen in the real enrollment files.
    u, later = rng.random(n), np.full(n, "none", dtype=object)
    stay, renewed = (acos.grp == "stayer").to_numpy(), (acos.grp == "early").to_numpy()
    later[stay & (u < 0.05)] = "renew2023"
    later[stay & (u >= 0.05) & (u < 0.15)] = "renew2024"
    later[stay & (u >= 0.15) & (u < 0.25)] = "leave2023"
    later[stay & (u >= 0.25) & (u < 0.32)] = "leave2024"
    later[renewed & (u < 0.1)] = "renew2024"
    acos["later"] = later
    # Per-capita spending: ACO level x common growth x the planted effect of early renewal from PY2022 (H4).
    acos["pc_level"] = 12_000 * rng.lognormal(0, 0.15, n)
    acos["did_effect"] = did_effect
    acos["basic"] = rng.random(n) < 0.8
    acos["basic_level"] = np.where(acos.basic, rng.choice(list("ABCDE"), n, p=[0.1, 0.5, 0.15, 0.05, 0.2]), None)
    acos["high_revenue"] = rng.random(n) < 0.35
    acos["prospective"] = rng.random(n) < 0.4
    acos["sav_rate_2020"] = rng.normal(2.0, 4.0, n)
    acos["sav_rate_2021"] = rng.normal(2.5, 4.0, n)
    acos["n_ab_2020"] = rng.integers(5_000, 60_000, n)
    hist_2022 = new * rng.lognormal(0.0, hist_noise, n) if hist_noise > 0 else new

    _write_enrollment(out_dir, acos)
    cms_by = own * rng.lognormal(0.0, by_noise, own.shape) if by_noise > 0 else own
    _write_results(out_dir, acos, own, cms_by, shares_py, py_hidden, aco_risk, risk_hidden, current, hist_2022, rng)
    _write_county(out_dir, states, counties, county_pc, county_py, county_ok, county_risk)
    _write_assignment(out_dir, ids, states, counties, ab)
    return Truth(
        acos=acos,
        unrecoverable=ids[unrecoverable],
        zero_share=ids[zero_share],
        imputed_ids=[ids[some_hidden], ids[all_hidden], ids[share_hidden], ids[6], ids[7]],
        early_ids=list(acos.aco_id[early]),
    )


def _enrollment_rows(a: pd.Series) -> dict[str, tuple[int, int]]:
    """Agreement (start year/month, period) shown in each enrollment file for one ACO."""
    rows: dict[str, tuple[int, int]] = {}
    if a.kind in ("base19", "base20"):
        before = {"new": None, "initial2016": ((2016, 1), 1), "renewal2017": ((2017, 1), 2)}[a.prior]
        period = 1 if before is None else before[1] + 1
        if before is not None:
            first = 2016 if a.prior == "initial2016" else 2017
            for f in ("2016", "2017", "2018", "2019a", "2019b"):
                if int(f[:4]) >= first and not (a.kind == "base19" and f == "2019b"):
                    rows[f] = (before[0], before[1])
        start = (2019, 7) if a.kind == "base19" else (2020, 1)
        for f in (["2019b"] if a.kind == "base19" else []) + ["2020", "2021"]:
            rows[f] = (start, period)
        if a.grp in ("early", "stayer"):
            for year in (2022, 2023, 2024):
                agreement = _post_agreement(a, year, start, period)
                if agreement is not None:
                    rows[str(year)] = agreement
    elif a.kind == "valid":
        period = 2 if a.prior == "renewal2018" else 1
        for f in ("2018", "2019a", "2019b", "2020", "2021"):
            rows[f] = ((2018, 1), period)
        for f in ("2022", "2023", "2024"):
            rows[f] = ((2022, 1), period + 1)
    else:
        for f in ("2021", "2022", "2023", "2024"):
            rows[f] = ((2021, 1), 1)
    return rows


def _post_agreement(a: pd.Series, year: int, start: tuple[int, int], period: int):
    """Agreement (start, period) of an early renewer or stayer in PY2022-PY2024, or None once it has left."""
    later = a.later
    if later == "leave2023" and year >= 2023 or later == "leave2024" and year >= 2024:
        return None
    if a.grp == "early":
        return ((2024, 1), period + 2) if later == "renew2024" and year >= 2024 else ((2022, 1), period + 1)
    if later == "renew2023" and year >= 2023:
        return ((2023, 1), period + 1)
    if later == "renew2024" and year >= 2024:
        return ((2024, 1), period + 1)
    return (start, period)


def _write_enrollment(out_dir: Path, acos: pd.DataFrame) -> None:
    files: dict[str, list[dict]] = {f: [] for f in config.ENROLLMENT_FILES}
    for _, a in acos.iterrows():
        for f, ((y, m), period) in _enrollment_rows(a).items():
            row = {"aco_id": a.aco_id, "aco_name": f"Synthetic ACO {a.aco_id} Médical", "agreement_period_num": period}
            row["initial_start_date"] = _mdy(y, m)
            row["current_start_date"] = _mdy(y, m, suffix=" 0:00" if f == "2019a" else "")
            if f >= "2019b":
                level = a.basic_level if a.basic else ""
                row.update(basic_track=int(a.basic), basic_track_level=level, enhanced_track=int(not a.basic))
                row.update(high_revenue_aco=int(a.high_revenue), low_revenue_aco=int(not a.high_revenue))
            else:
                row.update(track_1=1, track_2=0, track_3=0)
            if f >= "2020":
                row.update(prospective_assignment=int(a.prospective), retrospective_assignment=int(not a.prospective))
            files[f].append(row)
    # Re-entering ACOs in 2022 without a PY2021 record: must not enter the validation sample.
    for j in range(3):
        files["2022"].append(
            {"aco_id": f"R{j}", "aco_name": "Re-entering", "agreement_period_num": 2, "initial_start_date": "1/1/2016", "current_start_date": "1/1/2022"}
        )
    for f, rows in files.items():
        pd.DataFrame(rows).to_csv(out_dir / config.ENROLLMENT_FILES[f], index=False, encoding="latin-1")


def _write_results(out_dir: Path, acos: pd.DataFrame, own, cms_by, shares_py, py_hidden, aco_risk, risk_hidden, current, hist_2022, rng) -> None:
    def fmt(x: float) -> str:
        return "*" if np.isnan(x) else f"{x:.6f}"

    for year, name in {**config.RESULTS_FILES, **config.DESCRIPTIVE_RESULTS_FILES}.items():
        id_col = "ACO_Num" if year in (2016, 2017) else "ACO_ID"
        sav_col = "Sav_Rate" if year == 2021 else "Sav_rate"
        rows = []
        for i, a in acos.iterrows():
            active = {
                2019: a.has_py2019 and a.kind != "other",
                2020: True,
                2021: True,
                2022: str(2022) in _enrollment_rows(a),
                2023: str(2023) in _enrollment_rows(a),
                2024: str(2024) in _enrollment_rows(a),
            }.get(year, a.kind in ("valid",) or a.prior != "new")
            if not active:
                continue
            row = {id_col: a.aco_id, "ACO_Name": f"Synthetic ACO {a.aco_id}", "N_AB": int(a.n_ab_2020)}
            # Results files' date format cannot be checked before registration; synthetic uses ISO dates here.
            row["Current_Start_Date"] = _results_start(a, year)
            treated = a.grp == "early" and year >= 2022
            row["Per_Capita_Exp_TOTAL_PY"] = f"{a.pc_level * 1.03 ** (year - 2019) * np.exp(a.did_effect * treated) * rng.lognormal(0, 0.03):.2f}"
            ages = rng.integers(500, 5_000, 4)
            row.update(N_Ben_Age_0_64=ages[0], N_Ben_Age_65_74=ages[1], N_Ben_Age_75_84=ages[2], N_Ben_Age_85plus=ages[3])
            female = int(ages.sum() * rng.uniform(0.5, 0.6))
            row.update(N_Ben_Female=female, N_Ben_Male=int(ages.sum()) - female)
            row[sav_col] = f"{a.sav_rate_2020 if year == 2020 else a.sav_rate_2021 if year == 2021 else rng.normal(1.5, 4.0):.4f}"
            row["UpdatedBnchmk"] = fmt(current[i] if year == 2021 else current[i] * 0.97)
            if year == 2022:
                # Early renewers' rows carry poison values; the loader must never admit them.
                row["HistBnchmk"] = fmt(hist_2022[i]) if a.kind == "valid" else "-999999"
                for k, t in enumerate(TYPES):
                    for b in (1, 2, 3):
                        row[f"Per_Capita_Exp_ALL_{t}_BY{b}"] = "-999999" if a.kind != "valid" else fmt(cms_by[i, b - 1, k])
                        row[f"CMS_HCC_RiskScore_{t}_BY{b}"] = "-999999" if a.kind != "valid" else fmt(aco_risk[i, b - 1, k])
            else:
                row["HistBnchmk"] = fmt(current[i] * 0.95)
            y_i = year - 2019
            for k, t in enumerate(TYPES):
                row[f"Per_Capita_Exp_ALL_{t}_PY"] = fmt(own[i, y_i, k]) if 0 <= y_i <= 2 else "1000"
                hidden = 0 <= y_i <= 2 and risk_hidden[i, y_i, k]
                row[f"CMS_HCC_RiskScore_{t}_PY"] = "*" if hidden else fmt(aco_risk[i, y_i, k]) if 0 <= y_i <= 2 else "1.0"
                row[RESULTS_SHARE_COLUMNS[t]] = "*" if year == 2021 and py_hidden[i, k] else f"{shares_py[i, k]:.1f}"
            row["N_AB_Year_PY"] = f"{np.round(shares_py[i], 1).sum():.1f}"
            rows.append(row)
        pd.DataFrame(rows).to_csv(out_dir / name, index=False, encoding="latin-1")


def _results_start(a: pd.Series, year: int) -> str:
    rows = _enrollment_rows(a)
    if str(year) in rows:
        (y, m), _ = rows[str(year)]
        return f"{y}-{m:02d}-01"
    if a.kind in ("base19", "base20"):
        return "2019-07-01" if a.kind == "base19" else "2020-01-01"
    return "2018-01-01" if a.kind == "valid" else "2021-01-01"


def _write_county(out_dir: Path, states, counties, county_pc, county_py, county_ok, county_risk) -> None:
    for year, name in config.COUNTY_FILES.items():
        df = pd.DataFrame(
            {"YEAR": year, "STATE_NAME": [STATE_NAMES[s] for s in states], "COUNTY_NAME": [f"County {c}" for c in counties], "STATE_ID": states, "COUNTY_ID": counties}
        )
        for t in TYPES:
            df[f"PER_CAPITA_EXP_{t}"] = [f"{v:.4f}" if ok else "*" for v, ok in zip(county_pc[year][t], county_ok[year][t], strict=True)]
            df[f"AVG_RISK_SCORE_{t}"] = [f"{v:.6f}" for v in county_risk[year][t]]
            df[f"PERSON_YEARS_{t}"] = [f"{v:.2f}" for v in county_py[year][t]]
        df.to_csv(out_dir / name, index=False, encoding="latin-1")


def _write_assignment(out_dir: Path, ids, states, counties, ab) -> None:
    rows = []
    for i, aco_id in enumerate(ids):
        for c in np.flatnonzero(ab[i].sum(1) > 0):
            row = {
                "Year": 2021,
                "ACO_ID": aco_id,
                "State_Name": STATE_NAMES[states[c]],
                "County_Name": f"County {counties[c]}",
                "State_ID": states[c],
                "County_ID": counties[c],
            }
            for k, t in enumerate(TYPES):
                row[f"AB_Psn_Yrs_{t}"] = f"{ab[i, c, k]:.1f}"
            row["Tot_AB_Psn_Yrs"] = f"{ab[i, c].sum():.1f}"
            row["Tot_AB"] = int(ab[i, c].sum())
            rows.append(row)
    pd.DataFrame(rows).to_csv(out_dir / config.ASSIGNMENT_FILE, index=False, encoding="latin-1")
